    private final boolean chinese;

    public FxLanguage(PackOutput output, String locale) {
        super(output, FxEasy.MODID, locale);
        this.chinese = "zh_cn".equals(locale);
    }

    @Override
    protected void addTranslations() {
        for (Entry entry : ENTRIES) {
            add(entry.key(), this.chinese ? entry.chinese() : entry.english());
        }
    }

    private static List<Entry> entries() {
        List<Entry> entries = new ArrayList<>(BASE);
        for (MarketEventDefinition definition : MarketEventCatalog.ALL) {
            Wording wording = EVENT_WORDING.get(definition.id());
            if (wording == null) {
                throw new IllegalStateException("market event " + definition.id() + " has no wording");
            }
            entries.add(new Entry(definition.titleKey(), wording.title(), wording.chineseTitle()));
            entries.add(new Entry(definition.bodyKey(), wording.body(), wording.chineseBody()));
        }
        return List.copyOf(entries);
    }

